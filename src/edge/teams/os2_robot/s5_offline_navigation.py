"""OS2-5: Autonomous Offline Pathway Navigation

Mission : The robot keeps navigating and avoiding obstacles while the WAN is cut. Telemetry
          is logged to the durable outbox and delivered after the link comes back.
Concept : Local control never waits for the network. The navigation loop (50 ms, absolute
          monotonic deadlines) only talks to local SQLite. A separate sync thread drains the
          outbox, but only while the WAN flag says "online". Zero loss is checked by event
          conservation: events stored == events delivered, no duplicates.

Owner   : (write names here)
Test    : tests/os2/test_s5_offline_navigation.py
Run     : PYTHONPATH=src python -m edge.teams.os2_robot.s5_offline_navigation [--offline 600]
          (--offline is the outage length in seconds. Default 10; use 600 for the 10-minute
          signature run. All lengths are counted in 50 ms ticks, not wall time.)

Data (generated by scripts/generate_os2_sim_data.py, fixed seed, labelled in the files):
  data/os2_central_park_pathway2_SAMPLE.geojson  APPROXIMATE Central Park waterside path the
        robot drives along at 0.5 m/s; every telemetry tick has a real-world lat/lon on it.
  data/os2_sensor_trace_SIMULATED.csv  one LiDAR reading per 50 ms tick: pedestrians and dogs
        come closer than 0.8 m (must e-stop), cyclists pass at 1.0-1.8 m (must NOT e-stop).
  IMU_YAW_RATE is derived from the path's curvature while the robot moves (0 when stopped).
The loop reuses the OS2-3 SafetyLatch and the shared RuleEngine with the e-stop rule from
config/os2.yaml. Phases: online -> WAN cut -> restored. --track FILE saves the driven track.
"""
import argparse
import csv
import json
import math
import os
import random
import sys
import tempfile
import threading
import time

from edge.config import load_config
from edge.models import SensorEvent
from edge.storage import Storage
from edge.decision import RuleEngine
from edge.teams.os2_robot.s3_estop_ttl import SafetyLatch

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
PERIOD_S = 0.05
CRUISE_MPS = 0.5
STOP_BELOW_M, CLEAR_ABOVE_M = 0.8, 1.0
PATH_FILE = os.path.join(ROOT, "data", "os2_central_park_pathway2_SAMPLE.geojson")
TRACE_FILE = os.path.join(ROOT, "data", "os2_sensor_trace_SIMULATED.csv")


def _ensure_data():
    if not (os.path.exists(PATH_FILE) and os.path.exists(TRACE_FILE)):
        import subprocess
        subprocess.run([sys.executable, os.path.join(ROOT, "scripts", "generate_os2_sim_data.py")],
                       check=True, stdout=subprocess.DEVNULL)


def load_trace():
    """List of (lidar_m, obstacle_id, obstacle_type), one per 50 ms tick."""
    with open(TRACE_FILE) as f:
        rows = [r for r in csv.reader(f) if r and not r[0].startswith("#")]
    return [(float(r[2]), r[3], r[4]) for r in rows[1:]]


class Pathway:
    """Polyline in metres (local tangent plane) built from the GeoJSON LineString."""

    def __init__(self, path_file):
        with open(path_file) as f:
            feat = json.load(f)["features"][0]
        self.name = feat["properties"].get("name", feat.get("id", "pathway"))
        self.lonlat = feat["geometry"]["coordinates"]
        lon0, lat0 = self.lonlat[0]
        self.lat0, self.lon0 = lat0, lon0
        self.k_lat = 111320.0
        self.k_lon = 111320.0 * math.cos(math.radians(lat0))
        self.xy = [((lo - lon0) * self.k_lon, (la - lat0) * self.k_lat) for lo, la in self.lonlat]
        self.cum = [0.0]
        for (x1, y1), (x2, y2) in zip(self.xy, self.xy[1:]):
            self.cum.append(self.cum[-1] + math.hypot(x2 - x1, y2 - y1))
        self.length = self.cum[-1]
        self._seg = 0

    def pose(self, s):
        """(lat, lon, heading_rad) at arc length s (the robot turns around at the end)."""
        lap = s % (2 * self.length)
        s = lap if lap <= self.length else 2 * self.length - lap
        backwards = lap > self.length
        i = self._seg if self.cum[self._seg] <= s else 0
        while i < len(self.cum) - 2 and self.cum[i + 1] < s:
            i += 1
        while i > 0 and self.cum[i] > s:
            i -= 1
        self._seg = i
        (x1, y1), (x2, y2) = self.xy[i], self.xy[i + 1]
        seg = (self.cum[i + 1] - self.cum[i]) or 1e-9
        t = (s - self.cum[i]) / seg
        x, y = x1 + t * (x2 - x1), y1 + t * (y2 - y1)
        heading = math.atan2(y2 - y1, x2 - x1) + (math.pi if backwards else 0.0)
        return self.lat0 + y / self.k_lat, self.lon0 + x / self.k_lon, heading


def _sync_loop(st, stop):
    """The upstream sync worker: drains the outbox only while the WAN is online."""
    while not stop.is_set():
        if st.wan_online() and st.drain_outbox_to_sink(200):
            continue
        time.sleep(0.05)


def run(online_s=3.0, offline_s=10.0, restored_s=5.0, track=None):
    """Returns (ok, report_lines)."""
    cfg = load_config(os.path.join(ROOT, "config", "os2.yaml"))
    engine = RuleEngine(cfg["rules"])
    node = cfg["node"]["id"]
    phases = [("online", int(online_s / PERIOD_S)), ("WAN cut", int(offline_s / PERIOD_S)),
              ("restored", int(restored_s / PERIOD_S))]
    per = {name: {"ticks": 0, "episodes": 0, "engaged": 0, "unsafe": 0} for name, _ in phases}
    _ensure_data()
    trace = load_trace()
    path = Pathway(PATH_FILE)
    imu_noise = random.Random(7)
    obstacles = {}                  # obstacle_id -> [type, closest_m, latched_during_it]
    track_rows = []
    travelled = 0.0
    stopped_ticks = 0
    _, _, prev_heading = path.pose(0.0)
    start_pose = path.pose(0.0)

    with tempfile.TemporaryDirectory() as tmp:
        st = Storage(os.path.join(tmp, "os2_nav.db"), cfg["paths"]["schema"])
        st.set_wan_online(True)
        stop = threading.Event()
        syncer = threading.Thread(target=_sync_loop, args=(st, stop), daemon=True)
        syncer.start()

        latch = SafetyLatch()
        stamps, i, in_episode = [], 0, False
        base = {}
        deadline = time.monotonic()
        for name, n_ticks in phases:
            if name == "WAN cut":
                st.set_wan_online(False)
            elif name == "restored":
                base["end_pending"], base["end_sink"] = st.outbox_pending(), st.counts()["sink"]
                st.set_wan_online(True)
            for k in range(n_ticks):
                delay = deadline - time.monotonic()
                if delay > 0:
                    time.sleep(delay)
                deadline += PERIOD_S
                now = time.monotonic()
                stamps.append(now)

                d, obs_id, obs_type = trace[i % len(trace)]
                lat, lon, heading = path.pose(travelled)
                blocked = d < STOP_BELOW_M
                p = per[name]
                p["ticks"] += 1
                if blocked and not in_episode:            # one episode = below 0.8 m until clear >= 1.0 m
                    p["episodes"] += 1
                    in_episode = True
                elif in_episode and d >= CLEAR_ABOVE_M:
                    in_episode = False
                if latch.on_proximity(d):                 # SAFETY FIRST: latch before any disk write
                    p["engaged"] += 1
                ev = SensorEvent(node_id=node, sensor="LIDAR_PROXIMITY_M", value=d, unit="m")
                ev.received_at = time.time()
                st.insert_event_with_outbox(ev)           # then log durably; the network is never involved
                for dec in engine.evaluate(ev, now):
                    st.insert_decision(dec)
                    st.set_decision_status(dec.decision_id, latch.submit(dec, now))
                latch.try_release(d)
                velocity = 0.0 if latch.engaged else CRUISE_MPS
                if blocked and velocity != 0:
                    p["unsafe"] += 1                      # robot moved with an obstacle in front
                if obs_id:
                    o = obstacles.setdefault(obs_id, [obs_type, d, False])
                    o[1] = min(o[1], d)
                    o[2] = o[2] or latch.engaged

                # IMU: yaw rate follows the path's curvature while moving, ~0 when stopped
                dh = math.atan2(math.sin(heading - prev_heading), math.cos(heading - prev_heading))
                yaw = math.degrees(dh) / PERIOD_S + imu_noise.gauss(0, 0.3)
                prev_heading = heading
                imu = SensorEvent(node_id=node, sensor="IMU_YAW_RATE", value=round(yaw, 3), unit="deg_s")
                imu.received_at = time.time()
                st.insert_event_with_outbox(imu)

                if velocity == 0:
                    stopped_ticks += 1
                travelled += velocity * PERIOD_S
                if track is not None:
                    track_rows.append((i, name, round(lat, 7), round(lon, 7), d, round(yaw, 3),
                                       velocity, int(latch.engaged), obs_type))
                i += 1
                if name == "WAN cut" and k == min(10, n_ticks // 2):
                    base["cut_pending"], base["cut_sink"] = st.outbox_pending(), st.counts()["sink"]

        # nav loop is over: give the sync thread time to drain what is left
        t_end = time.monotonic() + 15 + st.outbox_pending() / 200
        while st.outbox_pending() > 0 and time.monotonic() < t_end:
            time.sleep(0.05)
        stop.set()
        syncer.join(5)

        rep = st.conservation_report()
        conn = st._connect()
        try:
            distinct = conn.execute("SELECT COUNT(DISTINCT event_id) FROM upstream_sink").fetchone()[0]
        finally:
            conn.close()

    if track:
        os.makedirs(os.path.dirname(os.path.abspath(track)) or ".", exist_ok=True)
        with open(track, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["tick", "phase", "lat", "lon", "lidar_m", "imu_yaw_deg_s", "velocity_mps",
                        "estop_latched", "obstacle_type"])
            w.writerows(track_rows)

    end_lat, end_lon, _ = path.pose(travelled)
    must_stop = [o for o in obstacles.values() if o[1] < STOP_BELOW_M]
    must_pass = [o for o in obstacles.values() if o[0] == "cyclist" and o[1] >= STOP_BELOW_M]
    gaps = [b - a for a, b in zip(stamps, stamps[1:])]
    max_gap_ms = 1000 * max(gaps)
    cut = per["WAN cut"]
    checks = {
        f"data: {path.name} ({path.length:.0f} m, SAMPLE geometry) + SIMULATED LiDAR trace "
        f"({len(trace)} ticks); drove {travelled:.1f} m from ({start_pose[0]:.5f}, {start_pose[1]:.5f}) "
        f"to ({end_lat:.5f}, {end_lon:.5f}), stopped {100 * stopped_ticks / max(1, len(stamps)):.0f} % of the time":
            travelled > 0,
        f"{len(must_stop)} pedestrians/dogs came closer than 0.8 m: e-stop latched for all "
        f"{sum(1 for o in must_stop if o[2])}": all(o[2] for o in must_stop) and len(must_stop) > 0,
        f"{len(must_pass)} cyclists passed at >= 0.8 m: no false e-stop for "
        f"{sum(1 for o in must_pass if not o[2])}": not any(o[2] for o in must_pass),
        f"{cut['ticks']} ticks ran during the WAN cut; longest gap between ticks over the whole run {max_gap_ms:.0f} ms "
        f"(limit {PERIOD_S * 6000:.0f} ms)": cut["ticks"] == phases[1][1] and max_gap_ms < PERIOD_S * 6000,
        "obstacle avoidance identical in every phase (every obstacle latched, robot never moved blocked): "
        + ", ".join(f"{n}: {v['engaged']}/{v['episodes']}" for n, v in per.items()):
            all(v["episodes"] >= 1 and v["engaged"] == v["episodes"] and v["unsafe"] == 0 for v in per.values()),
        f"outbox grew during the cut ({base.get('cut_pending')} -> {base.get('end_pending')} pending)":
            base.get("end_pending", 0) > base.get("cut_pending", 10 ** 9),
        f"nothing delivered during the cut (sink stayed at {base.get('cut_sink')})":
            base.get("end_sink") == base.get("cut_sink"),
        f"after restore the outbox drained to {rep['pending']} pending": rep["pending"] == 0,
        f"event conservation (LiDAR + IMU): {rep['events']} stored = {rep['sink']} delivered, {distinct} distinct (no duplicates)":
            rep["conserved"] and rep["events"] == rep["sink"] == distinct and rep["events"] == 2 * len(stamps),
    }
    return all(checks.values()), [f"{'ok ' if v else 'FAILED '}{k}" for k, v in checks.items()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", type=float, default=10.0, help="WAN outage length in seconds (600 = 10 min)")
    ap.add_argument("--track", help="save the driven track (lat, lon, lidar, imu, e-stop) as CSV")
    args = ap.parse_args()
    ok, lines = run(offline_s=args.offline, track=args.track)
    print(f"[{'PASS' if ok else 'FAIL'}] OS2-5 Autonomous offline pathway navigation")
    for line in lines:
        print("      ", line)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
